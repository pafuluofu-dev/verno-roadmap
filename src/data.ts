/** Встроенные треки: только на них ссылаются привычки и «мимо плана» */
export type BuiltinTrackId = 'A' | 'B' | 'C'

/** Любой трек — встроенный или свой (id вида t-…, живёт в localStorage) */
export type TrackId = string

export type ItemKind = 'course' | 'free' | 'practice' | 'milestone'

export interface Item {
  id: string
  track: TrackId
  kind: ItemKind
  title: string
  /** Инструктор, язык, пометки — выводится серым рядом с названием */
  meta?: string
  /** Что проходить, что пропускать, зачем */
  note: string
  /** Часы работы с практикой (то, что идёт в расписание) */
  hours: number
  /** Чистая длительность видео на Udemy, если есть */
  video?: number
  /** Коэффициент видео → работа, для подписи */
  factor?: number
  /** Необязательный шаг: можно снять галочкой «пропустить» */
  optional?: boolean
  /** Уже пройдено (Tilda) */
  done?: boolean
  /** Ссылка на сам материал: страница курса на Udemy, плейлист на YouTube, документация */
  url?: string
  /** Сколько в материале считаемых единиц — уроков, разделов, видео. Без него прогресс идёт в процентах */
  units?: number
  /** Как называть единицы в подписи «из 123 …» */
  unitWord?: string
  /** Сколько единиц пройдено на момент составления плана; дальше правится вручную и хранится в браузере */
  unitsDone?: number
  /** Польза шага для цели трека, 0–100: не «хороший ли курс», а насколько приближает к заказам или офферу за свои часы */
  value?: number
}

export interface Habit {
  track: BuiltinTrackId
  time: string
  text: string
}

